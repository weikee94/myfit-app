#!/usr/bin/env node
// Generates supabase/migrations/010_import_opengym_exercises.sql from a local
// clone of https://github.com/DuarteSantos8/openGym.
//
//   git clone --depth 1 https://github.com/DuarteSantos8/openGym.git /tmp/openGym
//   node scripts/import-opengym-exercises.mjs /tmp/openGym
//
// Licensing (see THIRD_PARTY_NOTICES.md):
// - Only entries with "textSource": "exercisedb" are imported. Their name, equipment,
//   muscles and instructions are MIT (ExerciseDB v1 via hasaneyldrm/exercises-dataset).
// - "description", "muscleMap" and every openGym-authored entry are AGPL-3.0 → skipped.
// - catalogue/media (stills + clips) is licensed from Gym visual and must NOT be copied
//   into other apps → no demo_url is set.

import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const repo = process.argv[2];
if (!repo) {
  console.error("Usage: node scripts/import-opengym-exercises.mjs <path-to-openGym-clone>");
  process.exit(1);
}

const root    = join(dirname(fileURLToPath(import.meta.url)), "..");
const outFile = join(root, "supabase/migrations/010_import_opengym_exercises.sql");
const srcDir  = join(repo, "catalogue/exercises");

// openGym equipment → MyFit equipment_type enum. Unlisted values become NULL.
const EQUIPMENT = {
  "body weight": "bodyweight", "assisted": "bodyweight",
  "dumbbell": "dumbbell",
  "barbell": "barbell", "ez barbell": "barbell", "olympic barbell": "barbell", "trap bar": "barbell",
  "cable": "cable",
  "leverage machine": "machine", "smith machine": "machine", "sled machine": "machine",
  "stationary bike": "machine", "upper body ergometer": "machine", "elliptical machine": "machine",
  "skierg machine": "machine", "stepmill machine": "machine",
  "band": "bands", "resistance band": "bands",
  "kettlebell": "kettlebell",
};

function category(ex) {
  if (ex.bodyPart !== "cardio" && ex.equipment !== "stationary bike") return "strength";
  if (/bike|cycle/.test(ex.name) || ex.equipment === "stationary bike") return "bike";
  if (/\brun\b|treadmill|stepmill|walk/.test(ex.name)) return "run";
  return "strength";
}

const SMALL = new Set(["a", "an", "and", "of", "on", "in", "to", "with", "the", "or", "v."]);
function titleCase(name) {
  return name
    .replace(/\s*\((male|female)\)\s*$/i, "")
    .split(" ")
    .map((w, i) => (i > 0 && SMALL.has(w) ? w : w.replace(/^([("]?)(\p{L})/u, (_, p, c) => p + c.toUpperCase())))
    .join(" ")
    .trim();
}

const sql = (s) => (s == null ? "NULL" : `'${String(s).replace(/'/g, "''")}'`);
const sqlArray = (xs) => `ARRAY[${xs.map(sql).join(",")}]::text[]`;

const seen = new Set();
const rows = [];
for (const file of readdirSync(srcDir).filter((f) => f.endsWith(".json")).sort()) {
  const ex = JSON.parse(readFileSync(join(srcDir, file), "utf8"));
  if (ex.textSource !== "exercisedb") continue;

  const name = titleCase(ex.name);
  const key  = name.toLowerCase();
  if (seen.has(key)) continue;
  seen.add(key);

  const muscles      = [...new Set([ex.target, ...(ex.secondaryMuscles ?? [])].filter(Boolean))];
  const instructions = (ex.instructions ?? []).map((step, i) => `${i + 1}. ${step}`).join("\n");

  rows.push(
    `(${sql(name)}, '${category(ex)}', ${sqlArray(muscles)}, ` +
    `${EQUIPMENT[ex.equipment] ? `'${EQUIPMENT[ex.equipment]}'` : "NULL"}::equipment_type, ` +
    `${sql(instructions || null)})`
  );
}

const out = `-- Generated by scripts/import-opengym-exercises.mjs — do not edit by hand.
-- ${rows.length} exercises from the openGym catalogue (github.com/DuarteSantos8/openGym),
-- limited to the MIT-licensed ExerciseDB-sourced entries. See THIRD_PARTY_NOTICES.md.
-- No images: openGym's exercise media is licensed from Gym visual and not reusable.
-- Idempotent: exercises whose name already exists (case-insensitive) are skipped.

INSERT INTO exercises (name, category, muscle_groups, equipment, instructions, demo_type, is_public)
SELECT v.name, v.category::exercise_category, v.muscle_groups, v.equipment, v.instructions, NULL, true
FROM (VALUES
${rows.join(",\n")}
) AS v(name, category, muscle_groups, equipment, instructions)
WHERE NOT EXISTS (SELECT 1 FROM exercises e WHERE lower(e.name) = lower(v.name));
`;

writeFileSync(outFile, out);
console.log(`Wrote ${rows.length} exercises to ${outFile}`);
